// The sources behind the app's health numbers and advice (the "Fonti scientifiche" page and the "Fonti" links).
//
//   node tools/build_health_sources.mjs          write web/health-sources-refs.js
//   node tools/build_health_sources.mjs --check  no network: every source the topics cite is in the file
//
// As for web/wellbeing-refs.js, a citation shown in the app is never typed by hand: the PubMed identifiers listed in
// HEALTH_SOURCE_IDS (web/index.base.html) are asked of PubMed (E-utilities). Sources that are not on PubMed are
// listed below with their official title and address.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const OUT = path.join(ROOT, 'web/health-sources-refs.js');

const OFFICIAL = {
  'efsa-water-2010': { cite: 'EFSA Panel on Dietetic Products, Nutrition and Allergies. Scientific Opinion on Dietary Reference Values for water. EFSA Journal 2010;8(3):1459', url: 'https://www.efsa.europa.eu/en/efsajournal/pub/1459' },
  'nih-ods': { cite: 'National Institutes of Health, Office of Dietary Supplements. Dietary Supplement Fact Sheets', url: 'https://ods.od.nih.gov/factsheets/list-all/' },
  'medlineplus-labs': { cite: 'U.S. National Library of Medicine. MedlinePlus: Laboratory Tests', url: 'https://medlineplus.gov/lab-tests/' }
};

// The identifiers the topics in web/index.base.html cite: the HEALTH_SOURCE_IDS block.
export function citedIds() {
  const text = fs.readFileSync(path.join(ROOT, 'web/index.base.html'), 'utf8');
  const block = text.match(/const HEALTH_SOURCE_TOPICS = \[([\s\S]*?)\n\];/);
  if (!block) throw new Error('HEALTH_SOURCE_TOPICS not found in web/index.base.html');
  const ids = new Set();
  for (const m of block[1].matchAll(/\brefs: \[([^\]]*)\]/g)) for (const q of m[1].matchAll(/'([^']+)'/g)) ids.add(q[1]);
  return [...ids];
}
const isPmid = (id) => /^\d{5,9}$/.test(id);

function cite(x) {
  const names = (x.authors || []).map((a) => a.name);
  // A committee opinion has no named authors on PubMed: the body that wrote it.
  const who = names.length > 3 ? names.slice(0, 3).join(', ') + ' et al' : (names.join(', ') || (/Obstet Gynecol/.test(x.source) ? 'American College of Obstetricians and Gynecologists' : ''));
  const year = (String(x.pubdate).match(/\d{4}/) || [''])[0];
  const title = String(x.title).replace(/\.$/, '');
  const where = x.source + (x.volume ? ' ' + x.volume + (x.issue ? '(' + x.issue + ')' : '') + (x.pages ? ':' + x.pages : '') : '');
  return (who ? who + '. ' : '') + year + '. ' + title + '. ' + where;
}

const ids = citedIds();
if (process.argv.includes('--check')) {
  const built = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  const missing = ids.filter((id) => !built.includes('"' + id + '":'));
  if (missing.length) { console.log('Missing sources:', missing.join(', ')); process.exit(1); }
  console.log(ids.length + ' sources, all in web/health-sources-refs.js');
  process.exit(0);
}

const refs = {};
const pmids = ids.filter(isPmid);
for (let i = 0; i < pmids.length; i += 80) {
  const chunk = pmids.slice(i, i + 80);
  const res = await fetch('https://eutils.ncbi.nlm.nih.gov/entrez/eutils/esummary.fcgi?db=pubmed&retmode=json&id=' + chunk.join(','));
  const json = await res.json();
  for (const id of chunk) {
    const x = json.result[id];
    if (!x || x.error) throw new Error('PubMed has no record ' + id);
    refs[id] = { cite: cite(x), pmid: id, url: 'https://pubmed.ncbi.nlm.nih.gov/' + id + '/' };
  }
  await new Promise((r) => setTimeout(r, 400));
}
for (const id of ids.filter((x) => !isPmid(x))) {
  if (!OFFICIAL[id]) throw new Error('No official entry for ' + id);
  refs[id] = OFFICIAL[id];
}
const sorted = Object.fromEntries(Object.keys(refs).sort().map((k) => [k, refs[k]]));
fs.writeFileSync(OUT, '// Generated by tools/build_health_sources.mjs from PubMed. Do not edit.\nself.NURVAN_HEALTH_REFS = ' + JSON.stringify(sorted, null, 1) + ';\n', 'utf8');
console.log(Object.keys(sorted).length + ' sources written');
for (const k of Object.keys(sorted)) console.log(k.padEnd(18), sorted[k].cite.slice(0, 120));
